import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { once } from 'node:events';
import { DatabaseSync } from 'node:sqlite';

test('多人接口与实际服务重启后读档', async t=>{
  const dir=await mkdtemp(join(tmpdir(),'playground-world-'));
  let child,base;
  async function start(){
    child=spawn(process.execPath,['server.js'],{env:{...process.env,PORT:'0',HOST:'127.0.0.1',DATA_DIR:dir},stdio:['ignore','pipe','pipe']});
    base=await new Promise((resolve,reject)=>{
      let output='';const timer=setTimeout(()=>reject(new Error('startup timeout')),10000);
      child.stdout.on('data',data=>{output+=data;const match=output.match(/port (\d+)/);if(match){clearTimeout(timer);resolve('http://127.0.0.1:'+match[1]);}});
      child.on('error',e=>{clearTimeout(timer);reject(e);});child.on('exit',code=>{clearTimeout(timer);reject(new Error('exit '+code));});
    });
  }
  async function stop(){if(child&&child.exitCode===null){const exited=once(child,'exit');child.kill();await exited;}}
  t.after(async()=>{await stop();assert.ok(resolve(dir).startsWith(resolve(tmpdir())+'\\')||resolve(dir).startsWith(resolve(tmpdir())+'/'));await rm(dir,{recursive:true,force:true});});
  const req=(path,body,cookie,origin)=>fetch(base+path,{method:body?'POST':'GET',headers:{...(body?{'Content-Type':'application/json'}:{}),...(cookie?{cookie}:{}),...(origin?{Origin:origin}:{})},body:body?JSON.stringify(body):undefined});
  await start();
  assert.equal((await req('/api/world/character')).status,401);
  const cookies=[];
  for(const name of ['游侠甲','法师乙']){const r=await req('/api/register',{username:name,password:'testing12345'});assert.equal(r.status,200);cookies.push(r.headers.get('set-cookie').split(';')[0]);}
  const [a,b]=cookies;
  assert.equal((await req('/api/world/join',{classId:'ranger'},a,'https://evil.test')).status,403);
  assert.equal((await req('/api/world/join',{classId:'invalid'},a)).status,400);
  const alice=await(await req('/api/world/join',{classId:'ranger'},a)).json();
  const bob=await(await req('/api/world/join',{classId:'mage'},b)).json();
  assert.equal(bob.players.length,2);
  assert.equal((await req('/api/world/action',{clientId:alice.clientId,type:'save'},b)).status,409);
  await req('/api/world/action',{clientId:alice.clientId,type:'input',dx:1,dy:0},a);
  await new Promise(r=>setTimeout(r,300));
  const saved=await(await req('/api/world/action',{clientId:alice.clientId,type:'save',gold:9999},a)).json();
  assert.ok(saved.me.x>410);assert.equal(saved.me.gold,30);
  const view=await(await req('/api/world/action',{clientId:bob.clientId,type:'input',dx:0,dy:0},b)).json();
  assert.ok(view.players.find(p=>p.name==='游侠甲').x>410);
  const chat=await(await req('/api/world/action',{clientId:alice.clientId,type:'chat',text:'一起探索！'},a)).json();
  assert.equal(chat.chat[0].text,'一起探索！');
  let guestCookie, otherGuestCookie, guest;
  await t.test('无需注册的游客可联机和保存，但不能冒充账号或其他游客', async()=>{
    assert.equal((await req('/api/world/join',{classId:'ranger',guest:true})).status,401);
    assert.equal((await req('/api/world/guest',{classId:'ranger'},null,'https://evil.test')).status,403);
    assert.equal((await req('/api/world/guest',{classId:'invalid'})).status,400);
    assert.equal((await req('/api/world/guest',{classId:'ranger'},a)).status,409);
    const response=await req('/api/world/guest',{classId:'knight'});
    assert.equal(response.status,200);
    assert.match(response.headers.get('set-cookie'),/HttpOnly; SameSite=Lax; Path=\/api\/world; Max-Age=604800/);
    guestCookie=response.headers.get('set-cookie').split(';')[0];guest=await response.json();
    assert.equal(guest.guest,true);assert.equal(guest.me.classId,'knight');
    assert.equal(guest.online,3);assert.ok(guest.playerId.startsWith('guest_'));
    assert.equal((await(await req('/api/me',null,guestCookie)).json()).user,null);
    assert.equal((await req('/api/games',{},guestCookie)).status,401);
    const other=await req('/api/world/guest',{classId:'mage'});
    otherGuestCookie=other.headers.get('set-cookie').split(';')[0];
    const otherGuest=await other.json();assert.notEqual(otherGuest.playerId,guest.playerId);
    assert.equal((await req('/api/world/action',{type:'save',clientId:guest.clientId},otherGuestCookie)).status,409);
    assert.equal((await req('/api/world/action',{type:'save',clientId:guest.clientId},a)).status,409);
    const buy=await(await req('/api/world/action',{type:'buy',clientId:guest.clientId},guestCookie)).json();
    assert.equal(buy.me.gold,15);assert.equal(buy.me.potions,4);
    const guestSave=await(await req('/api/world/action',{type:'save',clientId:guest.clientId,gold:9999},guestCookie)).json();
    assert.equal(guestSave.me.gold,15);
    const again=await(await req('/api/world/guest',{classId:'mage'},guestCookie)).json();
    assert.equal(again.playerId,guest.playerId);assert.equal(again.me.classId,'knight');
    assert.equal(again.me.potions,4);
    assert.equal((await req('/api/world/action',{type:'save',clientId:guest.clientId},guestCookie)).status,409);
    guest=again;
    const isolated=await(await req('/api/world/character',null,otherGuestCookie)).json();
    assert.equal(isolated.character.gold,30);
    await req('/api/world/action',{type:'leave',clientId:otherGuest.clientId},otherGuestCookie);
    await req('/api/world/action',{type:'leave',clientId:guest.clientId},guestCookie);
  });
  await stop();
  const storedDb=new DatabaseSync(join(dir,'games.sqlite'));
  assert.equal(storedDb.prepare('SELECT COUNT(*) AS n FROM users').get().n,2,'游客不能隐式创建账号');
  storedDb.prepare('UPDATE world_guests SET expires=0 WHERE id<>?').run(guest.playerId);
  storedDb.close();
  await start();
  await t.test('游客存档在服务重启后保留，过期身份与伪造 Cookie 被拒绝',async()=>{
    const storedGuest=await(await req('/api/world/character',null,guestCookie)).json();
    assert.equal(storedGuest.guest,true);assert.equal(storedGuest.character.potions,4);assert.equal(storedGuest.character.gold,15);
    const back=await(await req('/api/world/guest',{classId:'ranger'},guestCookie)).json();
    assert.equal(back.me.classId,'knight');assert.equal(back.playerId,guest.playerId);
    assert.equal((await req('/api/world/character',null,otherGuestCookie)).status,401);
    assert.equal((await req('/api/world/character',null,'world_guest='+'0'.repeat(64))).status,401);
    assert.equal((await req('/api/world/action',{type:'save',clientId:guest.clientId},guestCookie)).status,409);
  });
  const stored=await(await req('/api/world/character',null,a)).json();
  assert.ok(stored.character.x>410);assert.equal(stored.character.classId,'ranger');assert.equal(stored.character.gold,30);
  const resumed=await(await req('/api/world/join',{classId:'knight'},a)).json();
  assert.equal(resumed.me.classId,'ranger');assert.equal(resumed.me.name,'游侠甲');
  assert.equal((await req('/api/world/action',{clientId:alice.clientId,type:'save'},a)).status,409);
  assert.equal((await req('/world-client.js')).status,200);
  const sandbox=await req('/api/games/snake/play');assert.match(sandbox.headers.get('content-security-policy'),/connect-src 'none'/);
  let migratedCookie, migratedUser;
  await t.test('游客在注册时自动迁移，注册失败和登录旧账号不消耗游客进度',async()=>{
    assert.equal((await req('/api/world/register',{username:'游侠甲',password:'testing12345'},guestCookie)).status,409);
    assert.equal((await(await req('/api/world/character',null,guestCookie)).json()).character.potions,4);
    assert.equal((await req('/api/world/register',{username:'迁移用户',password:'testing12345'},guestCookie,'https://evil.test')).status,403);
    const login=await req('/api/login',{username:'游侠甲',password:'testing12345'},guestCookie);
    assert.equal(login.status,200);assert.equal((await login.json()).guestProgressTransferred,false);
    assert.equal((await(await req('/api/world/character',null,guestCookie)).json()).character.classId,'knight');
    const before=(await(await req('/api/world/character',null,guestCookie)).json()).character;
    const response=await req('/api/world/register',{username:'迁移用户',password:'testing12345',gold:9999},guestCookie);
    assert.equal(response.status,200);
    const result=await response.json();assert.equal(result.guestProgressTransferred,true);migratedUser=result.user;
    const setCookies=response.headers.getSetCookie();
    migratedCookie=setCookies.find(v=>v.startsWith('session=')).split(';')[0];
    assert.ok(setCookies.some(v=>v.startsWith('world_guest=;')&&v.includes('Path=/api/world; Max-Age=0')));
    const after=await(await req('/api/world/character',null,migratedCookie)).json();
    assert.equal(after.guest,false);assert.deepEqual(after.character,{...before,name:'迁移用户'});
    assert.equal((await req('/api/world/character',null,guestCookie)).status,401);
    assert.equal((await req('/api/world/register',{username:'重复迁移',password:'testing12345'},guestCookie)).status,409);
    assert.equal((await(await req('/api/world/character',null,a)).json()).character.classId,'ranger');
    const entered=await(await req('/api/world/join',{classId:'mage'},migratedCookie)).json();
    assert.equal(entered.me.classId,'knight');assert.equal(entered.me.potions,4);
  });
  await t.test('同一游客同时注册只能迁移一次，失败的注册不留下空账号',async()=>{
    const guestResponse=await req('/api/world/guest',{classId:'mage'});
    const racingCookie=guestResponse.headers.get('set-cookie').split(';')[0];
    const responses=await Promise.all(['并发甲','并发乙'].map(username=>req('/api/world/register',{username,password:'testing12345'},racingCookie)));
    assert.deepEqual(responses.map(r=>r.status).sort(),[200,409]);
    const won=await responses.find(r=>r.status===200).json();assert.equal(won.guestProgressTransferred,true);
  });
  await stop();await start();
  await t.test('迁移后的账号可重启读档，旧游客不可再使用',async()=>{
    const restored=await(await req('/api/world/character',null,migratedCookie)).json();
    assert.equal(restored.character.name,migratedUser.username);assert.equal(restored.character.potions,4);
    assert.equal(restored.character.gold,15);assert.equal(restored.character.classId,'knight');
    assert.equal((await req('/api/world/character',null,guestCookie)).status,401);
    const verifyDb=new DatabaseSync(join(dir,'games.sqlite'));
    assert.equal(verifyDb.prepare("SELECT COUNT(*) n FROM users WHERE username IN ('并发甲','并发乙')").get().n,1);
    assert.equal(verifyDb.prepare("SELECT COUNT(*) n FROM users WHERE username='重复迁移'").get().n,0);
    verifyDb.close();
  });
});
